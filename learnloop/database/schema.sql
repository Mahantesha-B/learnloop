-- LearnLoop -- Course/Quiz Platform
-- Import via phpMyAdmin or: mysql -u root -P 3306 < schema.sql
-- Creates the database, schema, and demo seed data.

CREATE DATABASE IF NOT EXISTS learnloop
    CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE learnloop;

SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS quiz_attempt_selections;
DROP TABLE IF EXISTS quiz_attempts;
DROP TABLE IF EXISTS quiz_options;
DROP TABLE IF EXISTS quiz_questions;
DROP TABLE IF EXISTS quizzes;
DROP TABLE IF EXISTS lesson_progress;
DROP TABLE IF EXISTS enrollments;
DROP TABLE IF EXISTS lessons;
DROP TABLE IF EXISTS courses;
DROP TABLE IF EXISTS users;
SET FOREIGN_KEY_CHECKS = 1;

-- ============================================================
-- Schema
-- ============================================================

CREATE TABLE users (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(150) NOT NULL UNIQUE,
    password      VARCHAR(255) NOT NULL,
    role          ENUM('super_admin','instructor','student') NOT NULL,
    status        ENUM('active','inactive') NOT NULL DEFAULT 'active',
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- A course is deactivated (status = 'inactive'), never deleted, once it has
-- enrollments -- see Course::delete()/deactivate() in app/models/Course.php.
CREATE TABLE courses (
    id              INT AUTO_INCREMENT PRIMARY KEY,
    title           VARCHAR(150) NOT NULL,
    description     TEXT NULL,
    instructor_id   INT NOT NULL,
    status          ENUM('active','inactive') NOT NULL DEFAULT 'active',
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (instructor_id) REFERENCES users(id),
    KEY idx_courses_instructor (instructor_id),
    KEY idx_courses_status (status)
) ENGINE=InnoDB;

-- content is plain text/markdown (see FEATURES.md -- no video hosting, no HTML editor).
CREATE TABLE lessons (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    course_id     INT NOT NULL,
    title         VARCHAR(150) NOT NULL,
    content       TEXT NOT NULL,
    sort_order    INT NOT NULL,
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE CASCADE,
    UNIQUE KEY uniq_course_order (course_id, sort_order)
) ENGINE=InnoDB;

CREATE TABLE enrollments (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    student_id    INT NOT NULL,
    course_id     INT NOT NULL,
    enrolled_at   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE CASCADE,
    UNIQUE KEY uniq_student_course (student_id, course_id)
) ENGINE=InnoDB;

-- One row = this student has marked this lesson complete. Its mere existence
-- (or absence) for lesson N-1 is what LessonController checks server-side
-- before allowing a GET on lesson N -- see FEATURES.md design notes.
CREATE TABLE lesson_progress (
    id              INT AUTO_INCREMENT PRIMARY KEY,
    student_id      INT NOT NULL,
    lesson_id       INT NOT NULL,
    completed_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (lesson_id) REFERENCES lessons(id) ON DELETE CASCADE,
    UNIQUE KEY uniq_student_lesson (student_id, lesson_id)
) ENGINE=InnoDB;

-- One quiz per course (enforced by the UNIQUE key), owned by that course's instructor.
CREATE TABLE quizzes (
    id                    INT AUTO_INCREMENT PRIMARY KEY,
    course_id             INT NOT NULL,
    title                 VARCHAR(150) NOT NULL,
    pass_threshold_pct    INT NOT NULL DEFAULT 60,
    max_attempts          INT NOT NULL DEFAULT 2,
    created_at            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE CASCADE,
    UNIQUE KEY uniq_course_quiz (course_id)
) ENGINE=InnoDB;

CREATE TABLE quiz_questions (
    id                INT AUTO_INCREMENT PRIMARY KEY,
    quiz_id           INT NOT NULL,
    question_text     TEXT NOT NULL,
    question_type     ENUM('single','multi') NOT NULL DEFAULT 'single',
    sort_order        INT NOT NULL,
    FOREIGN KEY (quiz_id) REFERENCES quizzes(id) ON DELETE CASCADE,
    KEY idx_questions_quiz (quiz_id)
) ENGINE=InnoDB;

CREATE TABLE quiz_options (
    id                INT AUTO_INCREMENT PRIMARY KEY,
    question_id       INT NOT NULL,
    option_text       VARCHAR(255) NOT NULL,
    is_correct        TINYINT(1) NOT NULL DEFAULT 0,
    sort_order        INT NOT NULL,
    FOREIGN KEY (question_id) REFERENCES quiz_questions(id) ON DELETE CASCADE,
    KEY idx_options_question (question_id)
) ENGINE=InnoDB;

-- score_pct/passed are computed once at submission time (deterministic MCQ
-- grading, see FEATURES.md) and stored here -- never re-derived on read.
CREATE TABLE quiz_attempts (
    id                INT AUTO_INCREMENT PRIMARY KEY,
    quiz_id           INT NOT NULL,
    student_id        INT NOT NULL,
    attempt_number    INT NOT NULL,
    score_pct         DECIMAL(5,2) NOT NULL,
    passed            TINYINT(1) NOT NULL,
    started_at        DATETIME NOT NULL,
    submitted_at      DATETIME NOT NULL,
    FOREIGN KEY (quiz_id) REFERENCES quizzes(id) ON DELETE CASCADE,
    FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE,
    KEY idx_attempts_quiz_student (quiz_id, student_id)
) ENGINE=InnoDB;

-- One row per option a student selected on a given attempt/question (a multi-select
-- question can have several rows for the same attempt_id + question_id).
CREATE TABLE quiz_attempt_selections (
    id             INT AUTO_INCREMENT PRIMARY KEY,
    attempt_id     INT NOT NULL,
    question_id    INT NOT NULL,
    option_id      INT NOT NULL,
    FOREIGN KEY (attempt_id) REFERENCES quiz_attempts(id) ON DELETE CASCADE,
    FOREIGN KEY (question_id) REFERENCES quiz_questions(id) ON DELETE CASCADE,
    FOREIGN KEY (option_id) REFERENCES quiz_options(id) ON DELETE CASCADE,
    KEY idx_selections_attempt (attempt_id)
) ENGINE=InnoDB;

